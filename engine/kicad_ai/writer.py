"""Serialise a built Schematic to a .kicad_sch file (format 20230121, opens in KiCad 7-10)."""
import uuid
import datetime


def _q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _f(v):
    return "%g" % round(v, 4)


def _eff(size=1.27, hide=False, just=None, bold=False):
    j = " (justify %s)" % just if just else ""
    return "(effects (font (size %s %s)%s)%s%s)" % (_f(size), _f(size), " bold" if bold else "", j, " hide" if hide else "")


def _U():
    return str(uuid.uuid4())


def write_sch(sch, path, project=None):
    import os
    project = project or os.path.splitext(os.path.basename(path))[0]
    root = _U()
    lib = sch.lib
    used = {}
    for i in sch.insts:
        used[i.lib.lib_id] = i.lib
    for pw in sch.powers:
        used[pw["lib_id"]] = lib.get(pw["lib_id"])
    flags = getattr(sch, "flags", [])
    if flags:
        used["power:PWR_FLAG"] = lib.get("power:PWR_FLAG")

    o = []
    o.append("(kicad_sch (version 20230121) (generator eeschema)")
    o.append("  (uuid %s)" % root)
    o.append('  (paper "A4")')
    o.append("  (title_block (title %s) (date %s) (rev \"1\") (comment 1 \"Generated by kicad_ai engine - verified before writing\"))"
             % (_q(sch.title), _q(datetime.date.today().isoformat())))
    o.append("  (lib_symbols")
    for lid in sorted(used):
        o.append("    " + used[lid].embed())
    o.append("  )")
    for (x, y) in sch.junctions:
        o.append("  (junction (at %s %s) (diameter 0) (color 0 0 0 0) (uuid %s))" % (_f(x), _f(y), _U()))
    for (x, y) in sch.noconnects:
        o.append("  (no_connect (at %s %s) (uuid %s))" % (_f(x), _f(y), _U()))
    for (a, b, _net) in sch.wires:
        o.append("  (wire (pts (xy %s %s) (xy %s %s)) (stroke (width 0) (type default)) (uuid %s))"
                 % (_f(a[0]), _f(a[1]), _f(b[0]), _f(b[1]), _U()))
    for (pt, name, ang) in sch.labels:
        just = "left bottom" if ang in (0, 90) else "right bottom"
        o.append("  (label %s (at %s %s %d) (fields_autoplaced) %s (uuid %s))"
                 % (_q(name), _f(pt[0]), _f(pt[1]), ang, _eff(just=just), _U()))
    for (txt, x, y, size, bold) in sch.texts:
        o.append("  (text %s (at %s %s 0) %s (uuid %s))" % (_q(txt), _f(x), _f(y), _eff(size, just="left", bold=bold), _U()))

    def symbol(lib_id, ref, value, x, y, rot, unit, fields, footprint="", datasheet="~", power=False,
               flag=False, pins=(), mirror=None):
        mir = " (mirror %s)" % mirror if mirror else ""
        o.append("  (symbol (lib_id %s) (at %s %s %d)%s (unit %d) (in_bom %s) (on_board %s) (dnp no)"
                 % (_q(lib_id), _f(x), _f(y), rot, mir, unit, "no" if power else "yes", "no" if flag else "yes"))
        o.append("    (uuid %s)" % _U())
        just = fields.get("just")
        just = None if just == "center" else just
        if rot in (90, 270):
            just = None
        rx, ry = fields["ref"]; vx, vy = fields["val"]
        o.append("    (property \"Reference\" %s (at %s %s %d) %s)" % (_q(ref), _f(rx), _f(ry), rot if rot in (90, 270) else 0, _eff(hide=power, just=just)))
        o.append("    (property \"Value\" %s (at %s %s %d) %s)" % (_q(value), _f(vx), _f(vy), rot if rot in (90, 270) else 0, _eff(hide=flag, just=just)))
        o.append("    (property \"Footprint\" %s (at %s %s 0) %s)" % (_q(footprint), _f(x), _f(y), _eff(hide=True)))
        o.append("    (property \"Datasheet\" %s (at %s %s 0) %s)" % (_q(datasheet), _f(x), _f(y), _eff(hide=True)))
        for n in pins:
            o.append("    (pin %s (uuid %s))" % (_q(n), _U()))
        o.append("    (instances (project %s (path \"/%s\" (reference %s) (unit %d))))" % (_q(project), root, _q(ref), unit))
        o.append("  )")

    for i in sch.insts:
        c = i.comp
        symbol(i.lib.lib_id, i.ref, c.get("value", i.lib.lib_id.split(":")[1]), i.x, i.y, i.rot, i.unit,
               i.fields, c.get("footprint") or i.lib.default_footprint, c.get("datasheet") or i.lib.datasheet,
               pins=[p.number for p in i.pins], mirror=i.mirror)
    for pw in sch.powers:
        x, y = pw["at"]
        # value text placed beyond the symbol along its direction
        b = pw.get("gbox", pw["box"])
        cy, cx = (b[1] + b[3]) / 2, (b[0] + b[2]) / 2
        vx, vy = x, (b[1] - 1.27 if cy < y else b[3] + 1.27)
        if pw["rot"] in (90, 270):
            vx, vy = (b[0] - 1.27 - 2 if cx < x else b[2] + 1.27 + 2), y
        symbol(pw["lib_id"], pw["ref"], pw["net"], x, y, pw["rot"], 1,
               dict(just=None, ref=(x, y + 3.81), val=(vx, vy)), power=True,
               pins=[p.number for p in lib.get(pw["lib_id"]).pins])
    for k, (pt, net) in enumerate(flags, 1):
        symbol("power:PWR_FLAG", "#FLG%02d" % k, "PWR_FLAG", pt[0], pt[1], 0, 1,
               dict(just=None, ref=(pt[0], pt[1] - 1.9), val=(pt[0], pt[1] - 3.81)), power=True, flag=True,
               pins=["1"])
    o.append('  (sheet_instances (path "/" (page "1")))')
    o.append(")")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(o) + "\n")
